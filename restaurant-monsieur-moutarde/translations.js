function changeLanguage(lang) {
  // Update direction for Arabic
  if (lang === 'ar') {
    document.body.classList.add('rtl');
    document.documentElement.dir = 'rtl';
    document.documentElement.lang = 'ar';
  } else {
    document.body.classList.remove('rtl');
    document.documentElement.dir = 'ltr';
    document.documentElement.lang = lang;
  }

  // Update text elements
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[lang][key];
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });

  // Specifically handle the select option placeholder
  const selectPlaceholder = document.querySelector('#res-people option[value=""]');
  if (selectPlaceholder && translations[lang]['res_people_ph']) {
    selectPlaceholder.textContent = translations[lang]['res_people_ph'];
  }

  // Update button language display
  const btn = document.getElementById('lang-btn');
  const span = btn.querySelector('span');
  span.textContent = lang.toUpperCase();
  
  // Flag logic mapping
  const flagMap = { 'fr': 'fr', 'en': 'gb', 'ar': 'ma' };
  btn.querySelector('.lang-flag').src = `https://flagcdn.com/w20/${flagMap[lang]}.png`;
}